#pragma once

#include <QtGlobal>

namespace lanrdp {

// 从一条**已建立**的 TCP 连接取内核测得的往返时间（毫秒，四舍五入）。
//
// 为什么要问内核，而不是自己发一帧等对方回：
// · 自己发一帧要**改协议** —— 而心跳刻意是单向的（回复会乒乓成风暴），
//   新加一对 ping/echo 等于为一个诊断读数牵动协议版本；
// · 内核的这套数来自 TCP 时间戳与已确认的发送，**不加任何线上流量**，
//   也不需要对端配合 ⇒ 老版本对端照样能测。
//
// 代价是它只能给「网络往返」，给不了「采集到显示」的端到端延迟
//（后者要两端时钟同步，否则算出来是时钟偏置，不是延迟）。
//
// 返回 -1 的三种情形都当「取不到」处理，不编造 0：
// 描述符无效 / 未连接 / 系统不认这个 ioctl（Win10 1703 之前）。
// 0 是一个合法读数（回环上就是 0.05 ms 量级），所以不能用 0 表示失败。
int queryTcpRttMs(qintptr socketDescriptor);

} // namespace lanrdp
